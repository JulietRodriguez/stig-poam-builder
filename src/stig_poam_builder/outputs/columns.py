_RAW_SEVERITY = {Cat.CAT_I: "High", Cat.CAT_II: "Moderate", Cat.CAT_III: "Low"}


def raw_severity(item: PoamItem) -> str:
    """eMASS Raw Severity scale (Very Low / Low / Moderate / High / Very High).

    CAT I -> High, CAT II -> Moderate, CAT III -> Low. ACAS Critical (Nessus 4)
    -> Very High and ACAS Info (Nessus 0) -> Very Low. This follows the
    convention used by public POA&M tooling; adjust for your organization.
    """
    if item.kind == "ACAS" and item.nessus_severity == 4:
        return "Very High"
    if item.kind == "ACAS" and item.nessus_severity == 0:
        return "Very Low"
    return _RAW_SEVERITY[item.raw_cat]


def adjusted_severity(item: PoamItem) -> str:
    """Pre-fill for the eMASS "Severity" column from the effective CAT."""
    if item.cat is item.raw_cat:
        return raw_severity(item)
    return _RAW_SEVERITY[item.cat]


_FORMULA_PREFIXES = ("=", "+", "-", "@", "\t", "\r")


def safe_cell(value: Any) -> Any:
    """Neutralize spreadsheet formula injection.

    Checklist and scan text is untrusted. A finding detail starting with "="
    would become a live formula in Excel. Prefix such text with an apostrophe.
    """
    if isinstance(value, str) and value.startswith(_FORMULA_PREFIXES):
        return "'" + value
    return value


def _milestone(item: PoamItem) -> str:
    n = len(item.assets)
    noun = "device" if n == 1 else "devices"
    verify = "re-scan with ACAS" if item.kind == "ACAS" else "re-review the STIG checklist"
    return (
        f"M1: Remediate {n} {noun} per the recommended fix and {verify} to verify. "
        f"Due {item.scheduled_completion.isoformat()}"
    )


def _comments(item: PoamItem, result: BuildResult) -> str:
    parts = [f"Generated by stig-poam-builder from scan/checklist data as of {result.as_of}."]
    if len(item.controls) > 1:
        parts.append("Related controls: " + ", ".join(item.controls[1:]) + ".")
    if item.mapping_basis != "CCI":
        parts.append(f"Control mapping: {item.mapping_basis}.")
    if item.unmapped_ccis:
        parts.append("CCIs not found in CCI List: " + ", ".join(item.unmapped_ccis) + ".")
    if item.override_notes:
        parts.append("Severity overrides: " + "; ".join(item.override_notes) + ".")
    if item.iavas:
        parts.append("IAVM: " + ", ".join(item.iavas) + ".")
    if item.cves:
        parts.append("CVEs: " + ", ".join(item.cves) + ".")
    return " ".join(parts)


def emass_row(item: PoamItem, result: BuildResult) -> dict[str, Any]:
    rules = result.rules
    return {
        "POA&M Item ID": item.item_id,
        "Control Vulnerability Description": item.description,
        "Controls / APs": item.primary_control,
        "CCI": ", ".join(item.ccis),
        "Office/Org": rules.office_org,
        "Security Checks": item.security_checks,
        "Resources Required": rules.resources_required,
        "Scheduled Completion Date": item.scheduled_completion,
        "Milestone with Completion Dates": _milestone(item),
        "Milestone Changes": "",
        "Source Identifying Vulnerability": "\n".join(item.sources),
        "Status": item.status,
        "Comments": _comments(item, result),
        "Raw Severity": raw_severity(item),
        "Devices Affected": "\n".join(item.devices),
        "Mitigations": "",
        "Predisposing Conditions": "",
        "Severity": adjusted_severity(item),
        "Relevance of Threat": "",
        "Threat Description": "",
        "Likelihood": "",
        "Impact": "",
        "Impact Description": "",
        "Residual Risk Level": "",
        "Recommendations": item.fix_text,
    }


