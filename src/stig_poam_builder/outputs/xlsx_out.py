"""eMASS-style POA&M workbook (.xlsx).

Sheets:
  POA&M    - one row per POA&M item, eMASS-style columns
  Details  - analysis columns (CAT, mapping basis, CVEs, overrides, ...)
  Summary  - open items by CAT and control family
  About    - run metadata and the "not an official template" notice
"""

from __future__ import annotations

from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from .. import __version__
from ..poam import BuildResult
from ..summary import CATS, compute_summary
from .columns import DETAIL_COLUMNS, EMASS_COLUMNS, detail_row, emass_row, safe_cell

HEADER_FILL = PatternFill("solid", fgColor="1F3864")
HEADER_FONT = Font(bold=True, color="FFFFFF")
CAT_FILL = {
    "CAT I": PatternFill("solid", fgColor="F8D7DA"),
    "CAT II": PatternFill("solid", fgColor="FFF3CD"),
    "CAT III": PatternFill("solid", fgColor="E2EFDA"),
}
WIDTHS = {
    "Control Vulnerability Description": 60,
    "Milestone with Completion Dates": 45,
    "Source Identifying Vulnerability": 45,
    "Comments": 60,
    "Recommendations": 50,
    "Devices Affected": 22,
    "Security Checks": 34,
    "Finding Details": 60,
    "Severity Overrides": 40,
}


def _header(ws, columns: list[str]) -> None:
    ws.append(columns)
    for idx, name in enumerate(columns, start=1):
        cell = ws.cell(row=1, column=idx)
        cell.fill, cell.font = HEADER_FILL, HEADER_FONT
        cell.alignment = Alignment(wrap_text=True, vertical="center")
        ws.column_dimensions[get_column_letter(idx)].width = WIDTHS.get(name, 16)
    ws.freeze_panes = "B2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(columns))}1"


def write_xlsx(result: BuildResult, path: str | Path, system_name: str = "") -> Path:
    path = Path(path)
    wb = Workbook()

    ws = wb.active
    ws.title = "POA&M"
    _header(ws, EMASS_COLUMNS)
    date_col = EMASS_COLUMNS.index("Scheduled Completion Date") + 1
    for item in result.items:
        row = emass_row(item, result)
        ws.append([safe_cell(row[c]) for c in EMASS_COLUMNS])
        r = ws.max_row
        ws.cell(row=r, column=date_col).number_format = "mm/dd/yyyy"
        ws.cell(row=r, column=1).fill = CAT_FILL[item.raw_cat.value]
        for c in range(1, len(EMASS_COLUMNS) + 1):
            ws.cell(row=r, column=c).alignment = Alignment(wrap_text=True, vertical="top")

    ws2 = wb.create_sheet("Details")
    _header(ws2, DETAIL_COLUMNS)
    for item in result.items:
        row = detail_row(item)
        ws2.append([safe_cell(row[c]) for c in DETAIL_COLUMNS])

    summary = compute_summary(result)
    ws3 = wb.create_sheet("Summary")
    cat_names = [c.value for c in CATS]
    _header(ws3, ["Control Family", *cat_names, "Total Items", "Open Instances"])
    for fam, v in summary["by_family"].items():
        items = list(v["items"].values())
        ws3.append([fam, *items, sum(items), sum(v["instances"].values())])
    ws3.append(
        ["TOTAL", *summary["items_by_cat"].values(), summary["poam_items"],
         summary["open_instances"]]
    )  # fmt: skip
    ws3.cell(row=ws3.max_row, column=1).font = Font(bold=True)

    ws4 = wb.create_sheet("About")
    about = [
        ("Generated by", f"stig-poam-builder {__version__}"),
        ("System", system_name or "(not set)"),
        ("As of", result.as_of.isoformat()),
        ("Control mapping", f"NIST SP 800-53 Rev {result.rules.nist_revision}"),
        ("CCI List", result.catalog_label or "none"),
        ("Inputs", ", ".join(summary["inputs"]["files"])),
        (
            "Template notice",
            "eMASS-style layout based on publicly documented eMASS POA&M fields. "
            "Not an official DISA/eMASS template. Verify against your component's "
            "template before import. Risk-analysis columns are intentionally blank.",
        ),
    ]
    for k, v in about:
        ws4.append([k, safe_cell(v)])
        ws4.cell(row=ws4.max_row, column=1).font = Font(bold=True)
    ws4.column_dimensions["A"].width = 20
    ws4.column_dimensions["B"].width = 100

    wb.save(path)
    return path
